"""v3 campaign (docs/PLAN.md v3 + addendum): selected allocation (apa), dither-identified STN, new held-out pair.

Run:  python sweep_v3.py [--workers 4] [--compile-only]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parents[1]
V0 = P5 / "results" / "quat_dual_v0_2026-09-12"
V1 = P5 / "results" / "quat_v1_2026-09-12"
V2 = P5 / "results" / "quat_v2_2026-09-12"
OUT = P5 / "results" / "quat_v3_2026-09-12"
ALLOC = json.loads((OUT / "alloc_screen" / "selected.json").read_text(encoding="utf-8"))["allocation"]
PLATFORMS = ("x2", "cf2-rotor")
MISSIONS = ("roll", "full3", "hard45", "hardstep", "yaw360", "hard45b", "hardstep_b", "hard45c", "hardstep_c")
SMOOTH = ("roll", "full3", "hard45", "yaw360", "hard45b", "hard45c")
NEW_HELDOUT = ("hard45c", "hardstep_c")
CONTROLLERS = ("pid", "pid_res", "st_pid", "dual", "st_pid_v2", "dual_v2", "stn_ks_v2", "stn_dx_v3", "dual_stn_dx_v3")


def cell(p, m, c):
    return OUT / p / m / c


def job(args):
    p, m, c, kind = args
    sys.path.insert(0, str(HERE))
    from run_dual import run  # noqa: E402
    if kind == "G4":
        s = run(p, m, c, OUT / "gates" / "G4_clip" / p / m / c, allocation="clip")
    elif kind == "G5":
        s = run(p, m, c, OUT / "gates" / "G5_clip" / p / m / c, allocation="clip")
    else:
        s = run(p, m, c, cell(p, m, c), allocation=ALLOC)
    return p, m, c, kind, s["qerr_mean_rad"], s["z_min_m"], s["wall_s"]


def load_dir(d):
    return json.loads((d / "summary.json").read_text(encoding="utf-8"))


def geo(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))


def clip_layer(p, m, c):
    """clip-allocation summary for the same controller/mission (v0/v1/v2 folders) with z_min filled in."""
    for d in (V0, V1, V2):
        cd = d / p / m / c
        if (cd / "summary.json").exists():
            s = load_dir(cd)
            if "z_min_m" not in s:
                with (cd / "trace.csv").open(encoding="utf-8") as f:
                    s["z_min_m"] = min(float(r["z"]) for r in csv.DictReader(f))
            return s
    return None


def compile_report():
    S = {(p, m, c): load_dir(cell(p, m, c)) for p in PLATFORMS for m in MISSIONS for c in CONTROLLERS}
    L = ["# v3 campaign: attitude-priority allocation, dither-identified STN, new held-out pair", "",
         f"Generated by `experiments/quat_dual_v0/sweep_v3.py`. Allocation: **{ALLOC}** (selected by the declared screen).",
         "Admissible = mean < 1 rad, saturation < 0.5, z_min >= 0.05 m on every mission (declared in PLAN v3).",
         "Cells: ratio of mean q-error to `pid` under the same allocation; `CRASH` = z_min < 0.05 m.", "", "## Gates", ""]
    g4 = load_dir(OUT / "gates" / "G4_clip" / "x2" / "roll" / "dual_v2")["qerr_mean_rad"] == \
        load_dir(V2 / "x2" / "roll" / "dual_v2")["qerr_mean_rad"]
    L.append(f"- G4 clip-allocation rerun of v2 x2/roll/dual_v2 bit-identical: {'PASS' if g4 else 'FAIL'}")
    ok = g4
    for p in PLATFORMS:
        a = S[(p, "roll", "pid")]["qerr_mean_rad"]
        b = load_dir(OUT / "gates" / "G5_clip" / p / "roll" / "pid")["qerr_mean_rad"]
        rel = abs(a - b) / b
        L.append(f"- G5 {p}/roll/pid {ALLOC} vs clip: rel diff {rel:.2e} {'PASS' if rel <= 1e-12 else 'FAIL'}")
        ok &= rel <= 1e-12
    L.append(f"\n**Gates: {'PASS' if ok else 'FAIL'}**\n")

    adm = {}
    for p in PLATFORMS:
        L += [f"## {p}", "",
              "| controller | " + " | ".join(MISSIONS) + " | geo all 9 | geo smooth 6 | geo new held-out 2 | admissible |",
              "|---|" + "---|" * (len(MISSIONS) + 4)]
        for c in CONTROLLERS:
            cells, ok_c = [], True
            for m in MISSIONS:
                s = S[(p, m, c)]
                r = s["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"]
                crash = s["z_min_m"] < 0.05
                bad = crash or s["qerr_mean_rad"] >= 1.0 or s["saturation_fraction"] >= 0.5
                ok_c &= not bad
                cells.append(("CRASH " if crash else ("inadm " if bad else "")) + f"{r:.3f}")
            adm[(p, c)] = ok_c
            ratio = lambda ms, base="pid": geo([S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, base)]["qerr_mean_rad"] for m in ms])  # noqa: E731
            L.append(f"| {c} | " + " | ".join(cells) + f" | {ratio(MISSIONS):.3f} | {ratio(SMOOTH):.3f} | "
                     f"{ratio(NEW_HELDOUT):.3f} | {'yes' if ok_c else 'NO'} |")
        L.append("")

    def rel(p, a, b, ms):
        return geo([S[(p, m, a)]["qerr_mean_rad"] / S[(p, m, b)]["qerr_mean_rad"] for m in ms])

    L += ["## Declared claims (TPA read as the selected allocation)", "", "| claim | X2 | CF2 | holds on both |", "|---|---|---|---|"]
    both = lambda f: all(f(p) for p in PLATFORMS)  # noqa: E731
    L.append(f"| C1 pid, pid_res admissible on all 9 | {adm[('x2','pid')] and adm[('x2','pid_res')]} | "
             f"{adm[('cf2-rotor','pid')] and adm[('cf2-rotor','pid_res')]} | "
             f"{both(lambda p: adm[(p,'pid')] and adm[(p,'pid_res')])} |")
    L.append(f"| C2 ungated st_pid, dual admissible on all 9 | {adm[('x2','st_pid')] and adm[('x2','dual')]} | "
             f"{adm[('cf2-rotor','st_pid')] and adm[('cf2-rotor','dual')]} | "
             f"{both(lambda p: adm[(p,'st_pid')] and adm[(p,'dual')])} |")
    c3 = {p: (rel(p, "dual", "pid_res", MISSIONS), rel(p, "dual", "pid_res", NEW_HELDOUT)) for p in PLATFORMS}
    L.append(f"| C3 dual < pid_res (all 9 / new held-out) | {c3['x2'][0]:.3f} / {c3['x2'][1]:.3f} | "
             f"{c3['cf2-rotor'][0]:.3f} / {c3['cf2-rotor'][1]:.3f} | {all(v[0] < 1 and v[1] < 1 for v in c3.values())} |")
    yh = {p: all(all(v > 0 for v in S[(p, m, "stn_dx_v3")]["yhat_mean"]) for m in SMOOTH) for p in PLATFORMS}
    c4b = {p: rel(p, "stn_dx_v3", "pid", SMOOTH) for p in PLATFORMS}
    c4c = {p: rel(p, "dual_stn_dx_v3", "pid_res", MISSIONS) for p in PLATFORMS}
    L.append(f"| C4a dither Yhat > 0 on every axis, smooth missions | {yh['x2']} | {yh['cf2-rotor']} | {all(yh.values())} |")
    L.append(f"| C4b stn_dx_v3 < pid, smooth | {c4b['x2']:.3f} | {c4b['cf2-rotor']:.3f} | {all(v < 1 for v in c4b.values())} |")
    L.append(f"| C4c dual_stn_dx_v3 < pid_res, all 9 | {c4c['x2']:.3f} | {c4c['cf2-rotor']:.3f} | {all(v < 1 for v in c4c.values())} |")

    L += ["", "## Supplementary (not claims): other comparisons against pid_res, all 9 missions", "",
          "| controller | X2 | CF2 | admissible X2 / CF2 |", "|---|---|---|---|"]
    for c in ("dual", "dual_v2", "dual_stn_dx_v3", "st_pid_v2", "stn_ks_v2", "stn_dx_v3"):
        L.append(f"| {c} | {rel('x2', c, 'pid_res', MISSIONS):.3f} | {rel('cf2-rotor', c, 'pid_res', MISSIONS):.3f} | "
                 f"{adm[('x2', c)]} / {adm[('cf2-rotor', c)]} |")

    L += ["", f"## Allocation effect: {ALLOC} vs clip, same controller, 7 common missions (ratio of mean error)", "",
          "| platform | controller | geo ratio | crashes clip -> " + ALLOC + " |", "|---|---|---|---|"]
    for p in PLATFORMS:
        for c in ("pid", "pid_res", "st_pid", "dual", "st_pid_v2", "dual_v2", "stn_ks_v2"):
            rs, cc, ca = [], 0, 0
            for m in MISSIONS[:7]:
                cl = clip_layer(p, m, c)
                if cl is None:
                    continue
                rs.append(S[(p, m, c)]["qerr_mean_rad"] / cl["qerr_mean_rad"])
                cc += cl["z_min_m"] < 0.05
                ca += S[(p, m, c)]["z_min_m"] < 0.05
            if rs:
                L.append(f"| {p} | {c} | {geo(rs):.3f} | {cc} -> {ca} |")

    L += ["", "## Dither-identified sensitivity (stn_dx_v3, dual_stn_dx_v3)", "",
          "| platform | mission | controller | s_hat mean (x,y,z) | Yhat mean (x,y,z) | m mean [p; i; d] |", "|---|---|---|---|---|---|"]
    for p in PLATFORMS:
        for m in MISSIONS:
            for c in ("stn_dx_v3", "dual_stn_dx_v3"):
                s = S[(p, m, c)]
                mm = s["multiplier_mean"]
                L.append(f"| {p} | {m} | {c} | {', '.join(f'{v:+.2f}' for v in s['s_hat_mean'])} | "
                         f"{', '.join(f'{v:+.2f}' for v in s['yhat_mean'])} | "
                         f"{', '.join(f'{v:.2f}' for v in mm[0:3])}; {', '.join(f'{v:.2f}' for v in mm[3:6])}; "
                         f"{', '.join(f'{v:.2f}' for v in mm[6:9])} |")
    rows = [{"platform": p, "mission": m, "controller": c, "qerr_mean_rad": S[(p, m, c)]["qerr_mean_rad"],
             "ratio_vs_pid": S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"],
             "saturation_fraction": S[(p, m, c)]["saturation_fraction"], "z_min_m": S[(p, m, c)]["z_min_m"]}
            for p in PLATFORMS for m in MISSIONS for c in CONTROLLERS]
    with (OUT / "summary_v3.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (OUT / "REPORT_v3.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--compile-only", action="store_true")
    a = ap.parse_args()
    if not a.compile_only:
        todo = [(p, m, c, "run") for p in PLATFORMS for m in MISSIONS for c in CONTROLLERS
                if not (cell(p, m, c) / "summary.json").exists()]
        if not (OUT / "gates" / "G4_clip" / "x2" / "roll" / "dual_v2" / "summary.json").exists():
            todo.append(("x2", "roll", "dual_v2", "G4"))
        for p in PLATFORMS:
            if not (OUT / "gates" / "G5_clip" / p / "roll" / "pid" / "summary.json").exists():
                todo.append((p, "roll", "pid", "G5"))
        print(f"{len(todo)} jobs, allocation={ALLOC}, workers={a.workers}", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            for f in as_completed([ex.submit(job, t) for t in todo]):
                p, m, c, kind, err, zmin, wall = f.result()
                print(f"done {kind} {p}/{m}/{c}: {err:.6f} rad, z_min {zmin:.2f} ({wall:.0f} s)", flush=True)
    compile_report()


if __name__ == "__main__":
    main()
