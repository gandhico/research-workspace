"""v0 campaign: 2 platforms x 5 missions x 4 controllers, then the pre-declared report.

Regression gates (must pass before any comparison is read):
  G1  pid     == ACC 2027 PID(k_i=0.05k_q) baseline, relative diff <= 1e-9
  G2  pid_res ~= ACC 2027 Nengo CMG-on-PID(0.05),   relative diff <= 1e-5
      (direct vs Nengo backends agree to ~2e-6 in the paper)

Evaluation rules: docs/PLAN.md (declared before results).

Run:  python sweep_v0.py [--workers 4]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parents[1]
OUT = P5 / "results" / "quat_dual_v0_2026-09-12"
REF = Path(r"C:\Research\papers\ACC2027_Gate_Residual_Control\experiments\nengo_nef_replication_2026-08-29"
           r"\results\pid_baseline_2026-09-10\pid_baseline_summary.csv")
PLATFORMS = ("x2", "cf2-rotor")
MISSIONS = ("roll", "full3", "hard45", "hardstep", "yaw360")
CONTROLLERS = ("pid", "pid_res", "st_pid", "dual")


def cell_dir(p, m, c):
    return OUT / p / m / c


def run_cell(args):
    p, m, c = args
    sys.path.insert(0, str(HERE))
    from run_dual import run  # noqa: E402
    s = run(p, m, c, cell_dir(p, m, c))
    return p, m, c, s["qerr_mean_rad"], s["wall_s"]


def load(p, m, c):
    return json.loads((cell_dir(p, m, c) / "summary.json").read_text(encoding="utf-8"))


def compile_report():
    ref = {(r["platform"], r["mission"]): r for r in csv.DictReader(REF.open(encoding="utf-8"))
           if float(r["ki_factor"]) == 0.05}
    rows, gates = [], []
    for p in PLATFORMS:
        for m in MISSIONS:
            s = {c: load(p, m, c) for c in CONTROLLERS}
            e = {c: s[c]["qerr_mean_rad"] for c in CONTROLLERS}
            g1 = abs(e["pid"] - float(ref[(p, m)]["PID"])) / float(ref[(p, m)]["PID"])
            g2 = abs(e["pid_res"] - float(ref[(p, m)]["CMG_on_PID"])) / float(ref[(p, m)]["CMG_on_PID"])
            gates.append((p, m, g1, g2))
            row = {"platform": p, "mission": m}
            for c in CONTROLLERS:
                row[f"{c}_rad"] = e[c]
                row[f"{c}_sat"] = s[c]["saturation_fraction"]
                row[f"{c}_ratio"] = e[c] / e["pid"]
            for c in ("st_pid", "dual"):
                row[f"{c}_mult_mean"] = s[c]["multiplier_mean"]
                row[f"{c}_mult_min"] = min(s[c]["multiplier_min"])
                row[f"{c}_mult_max"] = max(s[c]["multiplier_max"])
            row["dual_vs_pid_res"] = e["dual"] / e["pid_res"]
            for c in ("pid_res", "dual"):
                row[f"{c}_res_rms"] = s[c]["residual_rms_Nm"]
            rows.append(row)

    OUT.mkdir(parents=True, exist_ok=True)
    flat = [{k: (json.dumps(v) if isinstance(v, list) else v) for k, v in r.items()} for r in rows]
    with (OUT / "summary.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(flat[0]))
        w.writeheader()
        w.writerows(flat)

    def geo(vals):
        return math.exp(sum(math.log(v) for v in vals) / len(vals))

    L = ["# v0 quaternion campaign: PID, PID+residual, self-tuned PID, dual", "",
         "Generated by `experiments/quat_dual_v0/sweep_v0.py`. Rules: `docs/PLAN.md` (declared before results).",
         "Mean quaternion-angle error [rad], 45 s, h = 0.5 ms, one deterministic run per cell.", "",
         "## Regression gates", "",
         "| platform | mission | G1 pid vs ACC PID (rel.) | G2 pid_res vs ACC Nengo CMG-on-PID (rel.) |",
         "|---|---|---|---|"]
    ok = True
    for p, m, g1, g2 in gates:
        ok &= (g1 <= 1e-9) and (g2 <= 1e-5)
        L.append(f"| {p} | {m} | {g1:.2e} {'PASS' if g1 <= 1e-9 else 'FAIL'} | {g2:.2e} {'PASS' if g2 <= 1e-5 else 'FAIL'} |")
    L += ["", f"**All gates: {'PASS' if ok else 'FAIL'}**", "", "## Error and ratio to pid", "",
          "| platform | mission | pid | pid_res | st_pid | dual | st_pid/pid | dual/pid | dual/pid_res | max sat |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        msat = max(r[f"{c}_sat"] for c in CONTROLLERS)
        L.append(f"| {r['platform']} | {r['mission']} | {r['pid_rad']:.5f} | {r['pid_res_rad']:.5f} | "
                 f"{r['st_pid_rad']:.5f} | {r['dual_rad']:.5f} | {r['st_pid_ratio']:.3f} | {r['dual_ratio']:.3f} | "
                 f"{r['dual_vs_pid_res']:.3f} | {msat:.4f} |")
    L += ["", "## Pre-declared aggregate: geometric mean of per-mission ratio vs pid", "",
          "| platform | pid_res | st_pid | dual | admissible (all < 1 rad, sat < 0.5) |", "|---|---|---|---|---|"]
    for p in PLATFORMS:
        pr = [r for r in rows if r["platform"] == p]
        adm = {c: all(r[f"{c}_rad"] < 1.0 and r[f"{c}_sat"] < 0.5 for r in pr) for c in CONTROLLERS}
        L.append(f"| {p} | {geo([r['pid_res_ratio'] for r in pr]):.3f} | {geo([r['st_pid_ratio'] for r in pr]):.3f} | "
                 f"{geo([r['dual_ratio'] for r in pr]):.3f} | "
                 + ", ".join(f"{c}:{'yes' if adm[c] else 'NO'}" for c in CONTROLLERS) + " |")
        smooth = [r for r in pr if r["mission"] != "hardstep"]
        L.append(f"| {p} (without Hardstep, reported separately) | {geo([r['pid_res_ratio'] for r in smooth]):.3f} | "
                 f"{geo([r['st_pid_ratio'] for r in smooth]):.3f} | {geo([r['dual_ratio'] for r in smooth]):.3f} | |")
    L += ["", "## Gain multipliers (self-tuning layer)", "",
          "Mean multiplier per gain and axis `[p_x,p_y,p_z, i_x,i_y,i_z, d_x,d_y,d_z]`; the box is [0.5, 1.5].", "",
          "| platform | mission | st_pid mean | st_pid min/max | dual mean | dual min/max |", "|---|---|---|---|---|---|"]
    for r in rows:
        fm = lambda v: "[" + ", ".join(f"{x:.2f}" for x in v) + "]"  # noqa: E731
        L.append(f"| {r['platform']} | {r['mission']} | {fm(r['st_pid_mult_mean'])} | "
                 f"{r['st_pid_mult_min']:.2f}/{r['st_pid_mult_max']:.2f} | {fm(r['dual_mult_mean'])} | "
                 f"{r['dual_mult_min']:.2f}/{r['dual_mult_max']:.2f} |")
    (OUT / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--compile-only", action="store_true")
    a = ap.parse_args()
    if not a.compile_only:
        todo = [(p, m, c) for p in PLATFORMS for m in MISSIONS for c in CONTROLLERS
                if not (cell_dir(p, m, c) / "summary.json").exists()]
        print(f"{len(todo)} cells to run with {a.workers} workers", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            futs = [ex.submit(run_cell, t) for t in todo]
            for f in as_completed(futs):
                p, m, c, err, wall = f.result()
                print(f"done {p}/{m}/{c}: {err:.6f} rad ({wall:.0f} s)", flush=True)
    compile_report()


if __name__ == "__main__":
    main()
