"""v2 campaign: authority- and validity-gated self-tuning (docs/PLAN.md, v2 declaration).

Runs the four v2 controllers on 5 original + 2 held-out missions x 2 platforms,
reruns two v1 cells bit-for-bit (G3), then compiles all v0/v1/v2 controllers
under the v2 admissibility rule (mean < 1 rad, saturation < 0.5, z_min > 0.2 m).

Run:  python sweep_v2.py [--workers 4] [--compile-only]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parents[1]
V0 = P5 / "results" / "quat_dual_v0_2026-09-12"
V1 = P5 / "results" / "quat_v1_2026-09-12"
OUT = P5 / "results" / "quat_v2_2026-09-12"
PLATFORMS = ("x2", "cf2-rotor")
MISSIONS = ("roll", "full3", "hard45", "hardstep", "yaw360")
HELDOUT = ("hard45b", "hardstep_b")
ALLM = MISSIONS + HELDOUT
SMOOTH = ("roll", "full3", "hard45", "yaw360", "hard45b")
V0C = ("pid", "pid_res", "st_pid", "dual")
V1C = ("st_pid_f", "dual_f", "stn", "stn_b", "dual_stn_b", "stn_b_ks", "dual_stn_b_ks")
V2C = ("st_pid_v2", "dual_v2", "stn_ks_v2", "dual_stn_ks_v2")
ALL = V0C + V1C + V2C
G3_CELLS = (("x2", "roll", "stn_b_ks"), ("cf2-rotor", "hardstep", "dual_stn_b"))


def cell(p, m, c, g3=False):
    if g3:
        return OUT / "g3_rerun" / p / m / c
    if c in V2C:
        return OUT / p / m / c
    if m in MISSIONS and c in V0C:
        return V0 / p / m / c
    return V1 / p / m / c


def run_cell(args):
    p, m, c, g3 = args
    sys.path.insert(0, str(HERE))
    from run_dual import run  # noqa: E402
    s = run(p, m, c, cell(p, m, c, g3))
    return p, m, c, g3, s["qerr_mean_rad"], s["z_min_m"], s["wall_s"]


def load(p, m, c, g3=False):
    d = cell(p, m, c, g3)
    s = json.loads((d / "summary.json").read_text(encoding="utf-8"))
    if "z_min_m" not in s:                                   # v0/v1 summaries: min over the 10 ms trace
        with (d / "trace.csv").open(encoding="utf-8") as f:
            s["z_min_m"] = min(float(r["z"]) for r in csv.DictReader(f))
    return s


def geo(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))


def compile_report():
    S = {(p, m, c): load(p, m, c) for p in PLATFORMS for m in ALLM for c in ALL}
    L = ["# v2 campaign: authority- and validity-gated self-tuning; all controllers under the v2 rule", "",
         "Generated by `experiments/quat_dual_v0/sweep_v2.py`. Declared in `docs/PLAN.md` (v2) before any v2 run.",
         "Admissible = mean error < 1 rad, rotor saturation < 0.5, and no ground contact (z_min > 0.2 m) in every mission.",
         "Cells: ratio of mean q-error to `pid`; `CRASH` marks z_min <= 0.2 m.", "", "## Gates", ""]
    ok = True
    for p, m, c in G3_CELLS:
        new, old = load(p, m, c, True)["qerr_mean_rad"], S[(p, m, c)]["qerr_mean_rad"]
        L.append(f"- G3 {p}/{m}/{c} bit-identical rerun of v1: {'PASS' if new == old else 'FAIL'}")
        ok &= new == old
    L.append(f"\n**Gates: {'PASS' if ok else 'FAIL'}**\n")
    for p in PLATFORMS:
        L += [f"## {p}", "", "| controller | " + " | ".join(ALLM) + " | geo all 7 | geo smooth 5 | admissible |",
              "|---|" + "---|" * (len(ALLM) + 3)]
        for c in ALL:
            cells, adm = [], True
            for m in ALLM:
                s = S[(p, m, c)]
                r = s["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"]
                crash = s["z_min_m"] <= 0.2
                bad = crash or s["qerr_mean_rad"] > 1.0 or s["saturation_fraction"] > 0.5
                adm &= not bad
                cells.append(("CRASH " if crash else ("inadm " if bad else "")) + f"{r:.3f}")
            g7 = geo([S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"] for m in ALLM])
            g5 = geo([S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"] for m in SMOOTH])
            name = f"**{c}**" if c in V2C else c
            L.append(f"| {name} | " + " | ".join(cells) + f" | {g7:.3f} | {g5:.3f} | {'yes' if adm else 'NO'} |")
        L.append("")
    L += ["## Declared claims", "",
          "| platform | claim | value | holds |", "|---|---|---|---|"]
    for p in PLATFORMS:
        for c in V2C:
            adm = all(S[(p, m, c)]["z_min_m"] > 0.2 and S[(p, m, c)]["qerr_mean_rad"] < 1.0
                      and S[(p, m, c)]["saturation_fraction"] < 0.5 for m in ALLM)
            L.append(f"| {p} | (i) {c} admissible on all 7 missions | — | {'yes' if adm else 'NO'} |")
        for d in ("dual_v2", "dual_stn_ks_v2"):
            ro = geo([S[(p, m, d)]["qerr_mean_rad"] / S[(p, m, "pid_res")]["qerr_mean_rad"]
                      for m in ("roll", "full3", "hard45", "yaw360")])
            rh = S[(p, "hard45b", d)]["qerr_mean_rad"] / S[(p, "hard45b", "pid_res")]["qerr_mean_rad"]
            L.append(f"| {p} | (ii) {d} < pid_res on smooth missions (original geo / held-out Hard45b) | "
                     f"{ro:.3f} / {rh:.3f} | {'yes' if ro < 1 and rh < 1 else 'NO'} |")
            g = geo([S[(p, m, d)]["qerr_mean_rad"] / S[(p, m, "pid_res")]["qerr_mean_rad"] for m in ALLM])
            L.append(f"| {p} | (iii) {d} < pid_res, geo over all 7 | {g:.3f} | {'yes' if g < 1 else 'NO'} |")
    L += ["", "## v2 gain multipliers and altitude", "",
          "| platform | mission | controller | m mean [p; i; d] | m max | z_min [m] | sat |", "|---|---|---|---|---|---|---|"]
    for p in PLATFORMS:
        for m in ALLM:
            for c in V2C:
                s = S[(p, m, c)]
                mm = s["multiplier_mean"]
                L.append(f"| {p} | {m} | {c} | {', '.join(f'{v:.2f}' for v in mm[0:3])}; "
                         f"{', '.join(f'{v:.2f}' for v in mm[3:6])}; {', '.join(f'{v:.2f}' for v in mm[6:9])} | "
                         f"{max(s['multiplier_max']):.2f} | {s['z_min_m']:.2f} | {s['saturation_fraction']:.3f} |")
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [{"platform": p, "mission": m, "controller": c, "qerr_mean_rad": S[(p, m, c)]["qerr_mean_rad"],
             "ratio_vs_pid": S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"],
             "saturation_fraction": S[(p, m, c)]["saturation_fraction"], "z_min_m": S[(p, m, c)]["z_min_m"],
             "diverged": S[(p, m, c)].get("diverged", False)}
            for p in PLATFORMS for m in ALLM for c in ALL]
    with (OUT / "summary_v2.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (OUT / "REPORT_v2.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--compile-only", action="store_true")
    a = ap.parse_args()
    if not a.compile_only:
        todo = [(p, m, c, False) for p in PLATFORMS for m in ALLM for c in V2C
                if not (cell(p, m, c) / "summary.json").exists()]
        todo += [(p, m, c, True) for p, m, c in G3_CELLS if not (cell(p, m, c, True) / "summary.json").exists()]
        print(f"{len(todo)} cells to run with {a.workers} workers", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            futs = [ex.submit(run_cell, t) for t in todo]
            for f in as_completed(futs):
                p, m, c, g3, err, zmin, wall = f.result()
                print(f"done {'G3 ' if g3 else ''}{p}/{m}/{c}: {err:.6f} rad, z_min {zmin:.2f} ({wall:.0f} s)", flush=True)
    compile_report()


if __name__ == "__main__":
    main()
