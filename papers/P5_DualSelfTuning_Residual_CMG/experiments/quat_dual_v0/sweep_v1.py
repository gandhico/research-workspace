"""v1 campaign: CMG STN-PID-PES (faithful and bounded), freeze-fixed v0 tuner, held-out missions.

Declared in docs/PLAN.md (v1 declaration + post-smoke addendum) before this sweep.
v0 controller results on the five original missions are read from the v0 folder
(G3 reruns st_pid/dual on two cells and requires bit-identical errors).

Run:  python sweep_v1.py [--workers 4] [--compile-only]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parents[1]
V0 = P5 / "results" / "quat_dual_v0_2026-09-12"
OUT = P5 / "results" / "quat_v1_2026-09-12"
REF = Path(r"C:\Research\papers\ACC2027_Gate_Residual_Control\experiments\nengo_nef_replication_2026-08-29"
           r"\results\pid_baseline_2026-09-10\pid_baseline_summary.csv")
PLATFORMS = ("x2", "cf2-rotor")
MISSIONS = ("roll", "full3", "hard45", "hardstep", "yaw360")
HELDOUT = ("hard45b", "hardstep_b")
V0C = ("pid", "pid_res", "st_pid", "dual")
V1C = ("st_pid_f", "dual_f", "stn", "stn_b", "dual_stn_b", "stn_b_ks", "dual_stn_b_ks")
ALL = V0C + V1C
G3_CELLS = (("x2", "roll", "st_pid"), ("x2", "roll", "dual"), ("cf2-rotor", "hardstep", "st_pid"),
            ("cf2-rotor", "hardstep", "dual"))


def cell(p, m, c, g3=False):
    if g3:
        return OUT / "g3_rerun" / p / m / c
    if m in MISSIONS and c in V0C:
        return V0 / p / m / c
    return OUT / p / m / c


def run_cell(args):
    p, m, c, g3 = args
    sys.path.insert(0, str(HERE))
    from run_dual import run  # noqa: E402
    s = run(p, m, c, cell(p, m, c, g3))
    return p, m, c, g3, s["qerr_mean_rad"], s.get("diverged", False), s["wall_s"]


def load(p, m, c, g3=False):
    return json.loads((cell(p, m, c, g3) / "summary.json").read_text(encoding="utf-8"))


def geo(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))


def compile_report():
    ref = {(r["platform"], r["mission"]): r for r in csv.DictReader(REF.open(encoding="utf-8"))
           if float(r["ki_factor"]) == 0.05}
    S = {(p, m, c): load(p, m, c) for p in PLATFORMS for m in MISSIONS + HELDOUT for c in ALL}
    L = ["# v1 campaign: CMG STN-PID-PES, bounded self-tuning, dual, held-out missions", "",
         "Generated by `experiments/quat_dual_v0/sweep_v1.py`. Declared in `docs/PLAN.md` (v1 + addendum).",
         "Mean quaternion-angle error [rad], 45 s, h = 0.5 ms, one deterministic run per cell.",
         "`*_ks` controllers are the post-smoke, exploratory known-sign ablation.", "", "## Gates", ""]
    ok = True
    for p in PLATFORMS:
        for m in MISSIONS:
            g1 = abs(S[(p, m, "pid")]["qerr_mean_rad"] - float(ref[(p, m)]["PID"])) / float(ref[(p, m)]["PID"])
            g2 = abs(S[(p, m, "pid_res")]["qerr_mean_rad"] - float(ref[(p, m)]["CMG_on_PID"])) / float(ref[(p, m)]["CMG_on_PID"])
            ok &= g1 <= 1e-9 and g2 <= 1e-5
    g3 = []
    for p, m, c in G3_CELLS:
        new, old = load(p, m, c, True)["qerr_mean_rad"], S[(p, m, c)]["qerr_mean_rad"]
        g3.append((p, m, c, new == old))
        ok &= new == old
    L.append(f"- G1/G2 (all 10 original cells): {'PASS' if ok else 'see details'}")
    for p, m, c, eq in g3:
        L.append(f"- G3 {p}/{m}/{c} bit-identical rerun: {'PASS' if eq else 'FAIL'}")
    L.append(f"\n**All gates: {'PASS' if ok else 'FAIL'}**\n")

    def table(missions, title):
        L.extend([f"## {title}", "", "Ratio of mean error to `pid` (lower is better); `DIV` = non-finite state, "
                  "`inadm` = mean > 1 rad or saturation > 0.5.", ""])
        for p in PLATFORMS:
            L.append(f"### {p}\n")
            L.append("| controller | " + " | ".join(missions) + " | geo-mean | geo-mean w/o step | admissible |")
            L.append("|---|" + "---|" * (len(missions) + 3))
            for c in ALL:
                cells, ratios, ratios_ns, adm = [], [], [], True
                for m in missions:
                    s, e0 = S[(p, m, c)], S[(p, m, "pid")]["qerr_mean_rad"]
                    r = s["qerr_mean_rad"] / e0
                    bad = s["qerr_mean_rad"] > 1.0 or s["saturation_fraction"] > 0.5
                    adm &= not bad
                    tag = "DIV" if s.get("diverged", False) else ("inadm " if bad else "")
                    cells.append(f"{tag}{r:.3f}" if not s.get("diverged", False) else "DIV")
                    ratios.append(r)
                    if "step" not in m:
                        ratios_ns.append(r)
                L.append(f"| {c} | " + " | ".join(cells) + f" | {geo(ratios):.3f} | {geo(ratios_ns):.3f} | "
                         f"{'yes' if adm else 'NO'} |")
            L.append("")

    table(MISSIONS, "Original missions")
    table(HELDOUT, "Held-out missions (declared before v1, used for no design decision)")

    L += ["## Direction agreement (rule: original and held-out must agree)", "",
          "| platform | claim | original (geo-mean) | held-out (geo-mean) | agree |", "|---|---|---|---|---|"]
    claims = (("st_pid_f < pid", "st_pid_f", "pid"), ("stn_b < pid", "stn_b", "pid"),
              ("dual_f < pid_res", "dual_f", "pid_res"), ("dual_stn_b < pid_res", "dual_stn_b", "pid_res"),
              ("dual_stn_b_ks < pid_res", "dual_stn_b_ks", "pid_res"))
    for p in PLATFORMS:
        for name, a, b in claims:
            ro = geo([S[(p, m, a)]["qerr_mean_rad"] / S[(p, m, b)]["qerr_mean_rad"] for m in MISSIONS])
            rh = geo([S[(p, m, a)]["qerr_mean_rad"] / S[(p, m, b)]["qerr_mean_rad"] for m in HELDOUT])
            L.append(f"| {p} | {name} | {ro:.3f} | {rh:.3f} | {'yes' if (ro < 1) == (rh < 1) else 'NO'} |")
    L += ["", "## STN mechanism: learned sensitivity and gain multipliers", "",
          "| platform | mission | controller | Yhat mean (x,y,z) | Yhat<0 frac | m mean [p; i; d] | blocked frac | sat |",
          "|---|---|---|---|---|---|---|---|"]
    for p in PLATFORMS:
        for m in MISSIONS + HELDOUT:
            for c in ("stn", "stn_b", "dual_stn_b", "stn_b_ks", "st_pid_f"):
                s = S[(p, m, c)]
                ym = s.get("yhat_mean")
                mm = s["multiplier_mean"]
                bl = s.get("stn_blocked_fraction")
                L.append(f"| {p} | {m} | {c} | {'' if ym is None else ', '.join(f'{v:+.2f}' for v in ym)} | "
                         f"{'' if s.get('yhat_negative_fraction') is None else f'{s['yhat_negative_fraction']:.2f}'} | "
                         f"{', '.join(f'{v:.2f}' for v in mm[0:3])}; {', '.join(f'{v:.2f}' for v in mm[3:6])}; "
                         f"{', '.join(f'{v:.2f}' for v in mm[6:9])} | "
                         f"{'' if bl is None else ', '.join(f'{v:.2f}' for v in bl)} | {s['saturation_fraction']:.3f} |")
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [{"platform": p, "mission": m, "controller": c, "qerr_mean_rad": S[(p, m, c)]["qerr_mean_rad"],
             "ratio_vs_pid": S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"],
             "saturation_fraction": S[(p, m, c)]["saturation_fraction"], "diverged": S[(p, m, c)].get("diverged", False)}
            for p in PLATFORMS for m in MISSIONS + HELDOUT for c in ALL]
    with (OUT / "summary_v1.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (OUT / "REPORT_v1.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--compile-only", action="store_true")
    a = ap.parse_args()
    if not a.compile_only:
        todo = [(p, m, c, False) for p in PLATFORMS for m in MISSIONS + HELDOUT for c in ALL
                if not (cell(p, m, c) / "summary.json").exists()]
        todo += [(p, m, c, True) for p, m, c in G3_CELLS if not (cell(p, m, c, True) / "summary.json").exists()]
        print(f"{len(todo)} cells to run with {a.workers} workers", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            futs = [ex.submit(run_cell, t) for t in todo]
            for f in as_completed(futs):
                p, m, c, g3, err, div, wall = f.result()
                print(f"done {'G3 ' if g3 else ''}{p}/{m}/{c}: {err:.6f} rad{' DIVERGED' if div else ''} ({wall:.0f} s)",
                      flush=True)
    compile_report()


if __name__ == "__main__":
    main()
