"""v4 campaign (docs/PLAN.md v4): body-axis PID baseline and identification-based gain correction, apa allocation.

References pid, pid_res, dual_v2 are the v3 cells (same allocation, same 9 missions).
Gates: G6 rerun of v3 x2/hardstep_c/dual_v2 with the v4-edited code is bit-identical;
       G7 cf2-rotor pid_body equals pid (diag(J) = j_tune on CF2).

Run:  python sweep_v4.py [--workers 4] [--compile-only]
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
P5 = HERE.parents[1]
V3 = P5 / "results" / "quat_v3_2026-09-12"
OUT = P5 / "results" / "quat_v4_2026-09-12"
ALLOC = json.loads((V3 / "alloc_screen" / "selected.json").read_text(encoding="utf-8"))["allocation"]
PLATFORMS = ("x2", "cf2-rotor")
MISSIONS = ("roll", "full3", "hard45", "hardstep", "yaw360", "hard45b", "hardstep_b", "hard45c", "hardstep_c")
REFS = ("pid", "pid_res", "dual_v2")
NEW = ("pid_body", "pid_res_body", "idgc_v4", "dual_idgc_v4")
ALL = REFS + NEW
M_BODY_X2 = (1 / 1.6564388, 1 / 1.43510296, 1 / 0.41983376)     # j_tune/diag(J) from the model (jbody check)


def cell(p, m, c):
    return (V3 if c in REFS else OUT) / p / m / c


def job(args):
    p, m, c, kind = args
    sys.path.insert(0, str(HERE))
    from run_dual import run  # noqa: E402
    out = OUT / "gates" / "G6" / p / m / c if kind == "G6" else OUT / p / m / c
    s = run(p, m, c, out, allocation=ALLOC)
    return p, m, c, kind, s["qerr_mean_rad"], s["z_min_m"], s["wall_s"]


def load_dir(d):
    return json.loads((d / "summary.json").read_text(encoding="utf-8"))


def geo(v):
    return math.exp(sum(math.log(x) for x in v) / len(v))


def compile_report():
    S = {(p, m, c): load_dir(cell(p, m, c)) for p in PLATFORMS for m in MISSIONS for c in ALL}
    L = ["# v4 campaign: body-axis PID baseline and identification-based gain correction", "",
         f"Generated by `experiments/quat_dual_v0/sweep_v4.py`. Allocation **{ALLOC}**; 45 s; 9 missions.",
         "pid, pid_res and dual_v2 are the v3 cells. Cells: mean q-error ratio to `pid`; CRASH = z_min < 0.05 m.",
         "Admissible = mean < 1 rad, saturation < 0.5, z_min >= 0.05 m on every mission.", "", "## Gates", ""]
    a = load_dir(OUT / "gates" / "G6" / "x2" / "hardstep_c" / "dual_v2")["qerr_mean_rad"]
    b = S[("x2", "hardstep_c", "dual_v2")]["qerr_mean_rad"]
    g6 = a == b
    L.append(f"- G6 v4-code rerun of v3 x2/hardstep_c/dual_v2 bit-identical: {'PASS' if g6 else 'FAIL'} ({a!r} vs {b!r})")
    rels = [abs(S[("cf2-rotor", m, "pid_body")]["qerr_mean_rad"] / S[("cf2-rotor", m, "pid")]["qerr_mean_rad"] - 1)
            for m in MISSIONS]
    g7 = max(rels) <= 1e-9
    L.append(f"- G7 cf2-rotor pid_body == pid on all 9 (max rel diff {max(rels):.1e}): {'PASS' if g7 else 'FAIL'}")
    L.append(f"\n**Gates: {'PASS' if g6 and g7 else 'FAIL'}**\n")

    adm = {}
    for p in PLATFORMS:
        L += [f"## {p}", "", "| controller | " + " | ".join(MISSIONS) + " | geo all 9 | admissible |",
              "|---|" + "---|" * (len(MISSIONS) + 2)]
        for c in ALL:
            cells, ok_c = [], True
            for m in MISSIONS:
                s = S[(p, m, c)]
                r = s["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"]
                crash = s["z_min_m"] < 0.05
                bad = crash or s["qerr_mean_rad"] >= 1.0 or s["saturation_fraction"] >= 0.5
                ok_c &= not bad
                cells.append(("CRASH " if crash else ("inadm " if bad else "")) + f"{r:.3f}")
            adm[(p, c)] = ok_c
            g = geo([S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"] for m in MISSIONS])
            L.append(f"| {c} | " + " | ".join(cells) + f" | {g:.3f} | {'yes' if ok_c else 'NO'} |")
        L.append("")

    def rel(p, x, y):
        return geo([S[(p, m, x)]["qerr_mean_rad"] / S[(p, m, y)]["qerr_mean_rad"] for m in MISSIONS])

    L += ["## Declared claims", "", "| claim | X2 | CF2 | holds |", "|---|---|---|---|"]
    fin = {p: [S[(p, m, "idgc_v4")]["multiplier_final"][0:3] for m in MISSIONS] for p in PLATFORMS}
    tgt = {"x2": M_BODY_X2, "cf2-rotor": (1.0, 1.0, 1.0)}
    dev = {p: max(abs(v[k] / tgt[p][k] - 1) for v in fin[p] for k in range(3)) for p in PLATFORMS}
    L.append(f"| D1 final m near 1/(j_tune/diag J): max rel deviation over 9 missions x 3 axes | {dev['x2']:.1%} | "
             f"{dev['cf2-rotor']:.1%} | no threshold declared; reading +-15%: {all(d <= 0.15 for d in dev.values())} |")
    d2 = rel("x2", "pid_body", "pid")
    L.append(f"| D2 pid_body / pid (report) | {d2:.3f} | {rel('cf2-rotor', 'pid_body', 'pid'):.3f} | - |")
    d3 = (rel("x2", "idgc_v4", "pid"), rel("cf2-rotor", "idgc_v4", "pid"))
    L.append(f"| D3 idgc_v4 / pid (X2 < 1; CF2 in [0.97, 1.03]) | {d3[0]:.3f} | {d3[1]:.3f} | "
             f"{d3[0] < 1 and 0.97 <= d3[1] <= 1.03} |")
    d4 = {p: (rel(p, "dual_idgc_v4", "dual_v2"), rel(p, "dual_idgc_v4", "pid_res")) for p in PLATFORMS}
    d4ok = d4["x2"][0] < 1 and d4["x2"][1] < 1 and all(adm[(p, "dual_idgc_v4")] for p in PLATFORMS)
    L.append(f"| D4 dual_idgc_v4 / dual_v2 ; / pid_res (X2 both < 1; admissible both) | "
             f"{d4['x2'][0]:.3f} ; {d4['x2'][1]:.3f} | {d4['cf2-rotor'][0]:.3f} ; {d4['cf2-rotor'][1]:.3f} | {d4ok} |")
    L.append(f"| D5 residual gain on body-axis PID vs on j_tune PID: pid_res_body/pid_body vs pid_res/pid | "
             f"{rel('x2', 'pid_res_body', 'pid_body'):.3f} vs {rel('x2', 'pid_res', 'pid'):.3f} | "
             f"{rel('cf2-rotor', 'pid_res_body', 'pid_body'):.3f} vs {rel('cf2-rotor', 'pid_res', 'pid'):.3f} | - |")

    L += ["", "## Supplementary comparisons (geo over all 9 missions)", "", "| ratio | X2 | CF2 |", "|---|---|---|"]
    for x, y in (("idgc_v4", "pid_body"), ("dual_idgc_v4", "pid_res_body"), ("pid_res_body", "pid_res"),
                 ("dual_idgc_v4", "pid_body"), ("pid_body", "pid_res")):
        L.append(f"| {x} / {y} | {rel('x2', x, y):.3f} | {rel('cf2-rotor', x, y):.3f} |")

    L += ["", "## Identified ratio and final multipliers (idgc_v4, dual_idgc_v4)", "",
          "| platform | mission | controller | s_hat mean (x,y,z) | m final (x,y,z) | held fraction |", "|---|---|---|---|---|---|"]
    for p in PLATFORMS:
        for m in MISSIONS:
            for c in ("idgc_v4", "dual_idgc_v4"):
                s = S[(p, m, c)]
                L.append(f"| {p} | {m} | {c} | {', '.join(f'{v:.2f}' for v in s['s_hat_mean'])} | "
                         f"{', '.join(f'{v:.2f}' for v in s['multiplier_final'][0:3])} | "
                         f"{', '.join(f'{v:.3f}' for v in s['idgc_held_fraction'])} |")
    L.append(f"\nModel targets 1/(j_tune/diag J): X2 = {', '.join(f'{v:.3f}' for v in M_BODY_X2)}; CF2 = 1, 1, 1.")
    rows = [{"platform": p, "mission": m, "controller": c, "qerr_mean_rad": S[(p, m, c)]["qerr_mean_rad"],
             "ratio_vs_pid": S[(p, m, c)]["qerr_mean_rad"] / S[(p, m, "pid")]["qerr_mean_rad"],
             "saturation_fraction": S[(p, m, c)]["saturation_fraction"], "z_min_m": S[(p, m, c)]["z_min_m"]}
            for p in PLATFORMS for m in MISSIONS for c in ALL]
    with (OUT / "summary_v4.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    (OUT / "REPORT_v4.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--compile-only", action="store_true")
    a = ap.parse_args()
    if not a.compile_only:
        todo = [(p, m, c, "run") for p in PLATFORMS for m in MISSIONS for c in NEW
                if not (cell(p, m, c) / "summary.json").exists()]
        if not (OUT / "gates" / "G6" / "x2" / "hardstep_c" / "dual_v2" / "summary.json").exists():
            todo.insert(0, ("x2", "hardstep_c", "dual_v2", "G6"))
        print(f"{len(todo)} jobs, allocation={ALLOC}, workers={a.workers}", flush=True)
        with ProcessPoolExecutor(max_workers=a.workers) as ex:
            for f in as_completed([ex.submit(job, t) for t in todo]):
                p, m, c, kind, err, zmin, wall = f.result()
                print(f"done {kind} {p}/{m}/{c}: {err:.6f} rad, z_min {zmin:.2f} ({wall:.0f} s)", flush=True)
    compile_report()


if __name__ == "__main__":
    main()
