-- NIAG
-- Next Instruction Address Generation:
-- Top-level structural block
--
-- Purpose:
-- This component is the complete NIAG unit. It connects all
-- NIAG sub-blocks and produces:
--
--   1. MemAdrs -> the final next instruction address
--   2. RtnAdrs -> the return address for call instructions
--
-- Main idea:
-- NIAG computes several possible next addresses in parallel:
--
--   - NSA       : next sequential address
--   - AbsltAdrs : absolute jump address
--   - RelAdrs   : relative branch address
--   - RegAdrs   : register-based address
--   - RtnAdrs   : return address for calls
--
-- Then the MUX selects the correct final instruction address
-- according to:
--   - Sel  -> address selection control
--   - Cond -> branch condition control
--   - Stat -> ALU status flags
--
-- ---------------------------------------------------------
-- Example:
--
-- Suppose:
--   PCin   = x"00000020"
--   Target = jump index field
--   Immed  = branch immediate
--   Reg    = register jump address
--
-- First, the NIAG sub-blocks calculate:
--   NSA    = PCin + 4
--   ABS    = {NSA(31:28), Target, "00"}
--   REL    = NSA + displacement
--   REG    = Reg
--   RTN    = PCin + 4
--
-- Then U_MUX chooses one of these addresses and sends it to
-- MemAdrs.
--
-- So this top-level block combines all NIAG functions into
-- one complete unit.
-- =========================================================



