library IEEE;
use IEEE.STD_LOGIC_1164.all;

use work.ALU_Pkg.all;
use work.NIAG_Pkg.all;

-- =========================================================
-- NIAG
-- Next Instruction Address Generation:
-- Top-level structural block
--
-- Purpose:
-- This component is the complete NIAG unit. It connects all
-- NIAG sub-blocks and produces:
--
--   1. MemAdrs -> the final next instruction address
--   2. RtnAdrs -> the return address for call instructions
--
-- Main idea:
-- NIAG computes several possible next addresses in parallel:
--
--   - NSA       : next sequential address
--   - AbsltAdrs : absolute jump address
--   - RelAdrs   : relative branch address
--   - RegAdrs   : register-based address
--   - RtnAdrs   : return address for calls
--
-- Then the MUX selects the correct final instruction address
-- according to:
--   - Sel  -> address selection control
--   - Cond -> branch condition control
--   - Stat -> ALU status flags
--
-- ---------------------------------------------------------
-- Example:
--
-- Suppose:
--   PCin   = x"00000020"
--   Target = jump index field
--   Immed  = branch immediate
--   Reg    = register jump address
--
-- First, the NIAG sub-blocks calculate:
--   NSA    = PCin + 4
--   ABS    = {NSA(31:28), Target, "00"}
--   REL    = NSA + displacement
--   REG    = Reg
--   RTN    = PCin + 4
--
-- Then U_MUX chooses one of these addresses and sends it to
-- MemAdrs.
--
-- So this top-level block combines all NIAG functions into
-- one complete unit.
-- =========================================================

entity NIAG is
	port (	

        -- 26-bit target field for absolute addressing
		  Target : in STD_LOGIC_VECTOR(25 downto 0);

        -- Sign-extended immediate for relative addressing
			Immed : in STD_LOGIC_VECTOR(31 downto 0);

        -- Register value for register-based addressing
			Reg : in STD_LOGIC_VECTOR(31 downto 0);

        -- Shift control for relative displacement
			Xshft : in STD_LOGIC;

        -- Current Program Counter input
			PCin : in STD_LOGIC_VECTOR(31 downto 0);

        -- Branch condition control
			Cond : in STD_LOGIC_VECTOR(2 downto 0);

        -- Address source select
			Sel : in STD_LOGIC_VECTOR(1 downto 0);

        -- ALU status flags
			Stat : in STAT_SIGNL_REC;

        -- Final next instruction address
			MemAdrs : out STD_LOGIC_VECTOR(31 downto 0);

        -- Return address for call instructions
			RtnAdrs : out STD_LOGIC_VECTOR(31 downto 0)
			);
			
end NIAG;
	
architecture structural of NIAG is

    -- Internal signals carrying the addresses generated by
    -- each NIAG sub-block.
		signal nsa_s : STD_LOGIC_VECTOR(31 downto 0);
		signal abs_s : STD_LOGIC_VECTOR(31 downto 0);
		signal rel_s : STD_LOGIC_VECTOR(31 downto 0);
		signal reg_s : STD_LOGIC_VECTOR(31 downto 0);
		
begin
		
    -- =====================================================
    -- TODO:
    -- Instantiate the Next Sequential Address block.
    --
    -- Input:
    --   PCin
    --
    -- Output:
    --   nsa_s
    -- =====================================================
	U_NSA : entity work.NIAG_NSA 
		port map (
			PC => PCin, 
			NSA => nsa_s
			);
	 
    -- =====================================================
    -- TODO:
    -- Instantiate the Absolute Address block.
    --
    -- Inputs:
    --   Target, nsa_s
    --
    -- Output:
    --   abs_s
    -- =====================================================
	U_ABS : entity work.NIAG_Abslt 
		port map (
			Index => Target, 
			NSA => nsa_s, 
			AbsltAdrs => abs_s
			);
	 
    -- =====================================================
    -- TODO:
    -- Instantiate the Relative Address block.
    --
    -- Inputs:
    --   Immed, Xshft, nsa_s
    --
    -- Output:
    --   rel_s
    -- =====================================================
	U_REL : entity work.NIAG_Rel
		port map (
			Immed => Immed, 
			Xshft => Xshft, 
			NSA => nsa_s, 
			RelAdrs => rel_s
			);
	 
    -- =====================================================
    -- TODO:
    -- Instantiate the Register Address block.
    --
    -- Input:
    --   Reg
    --
    -- Output:
    --   reg_s
    -- =====================================================
	U_REG : entity work.NIAG_Reg
		port map (
			Reg => Reg, 
			RegAdrs => reg_s 
			);
    -- =====================================================
    -- TODO:
    -- Instantiate the Return Address block.
    --
    -- Input:
    --   PCin
    --
    -- Output:
    --   RtnAdrs
    -- =====================================================
		U_RTN : entity work.NIAG_Rtn
		port map (
			PC => PCin, 
			RtnAdrs => RtnAdrs
			);
    -- =====================================================
    -- TODO:
    -- Instantiate the MUX block that selects the final next
    -- instruction address.
    --
    -- Inputs:
    --   nsa_s, abs_s, rel_s, reg_s, Cond, Sel, Stat
    --
    -- Output:
    --   MemAdrs
    -- =====================================================
	 	U_MUX : entity work.NIAG_MUX
		port map (
			NxtAdrs => nsa_s, 
			AbsltAdrs => abs_s,
			RelAdrs => rel_s,
			RegAdrs => reg_s,
			Cond => Cond, 
			Sel =>  Sel, 
			Stat => Stat, 
			InstrAdrs => MemAdrs 
			);

end structural;
	 

	 
	 