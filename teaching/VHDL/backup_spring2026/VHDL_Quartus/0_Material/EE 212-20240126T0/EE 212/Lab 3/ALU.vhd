Library IEEE;
use IEEE.STD_LOGIC_1164.all;

Library EE_212_ALU;
use EE_212_ALU.ALU_pkg.all;

ENTITY ALU IS

	PORT(AIN: IN STD_LOGIC_VECTOR(31 DOWNTO 0);
		  BIN: IN STD_LOGIC_VECTOR(31 DOWNTO 0);
		  FUNC: IN STD_LOGIC_VECTOR(4 DOWNTO 0);
		  SHFT: IN STD_LOGIC_VECTOR(4 DOWNTO 0);
		  ROUT: OUT STD_LOGIC_VECTOR(31 DOWNTO 0);
		  STAT: OUT STAT_SIGNL_REC
	);
	
END ENTITY;

ARCHITECTURE BEHAVIORAL OF ALU IS

	SIGNAL LOREG: STD_LOGIC_VECTOR(31 DOWNTO 0);
	SIGNAL HIREG: STD_LOGIC_VECTOR(31 DOWNTO 0);
		
	BEGIN
	LABEL_ALU_ADD: ALU_ADD PORT MAP(AIN,BIN,FUNC,ROUT,STAT);
	LABEL_ALU_RDLO: ALU_RDLO PORT MAP(LOREG,FUNC,ROUT,STAT);
	LABEL_ALU_XOR: ALU_XOR PORT MAP(AIN,BIN,FUNC,ROUT,STAT);
	LABEL_ALU_RDHI: ALU_RDHI PORT MAP(HIREG,FUNC,ROUT,STAT);
	LABEL_ULU_MULS: ALU_MULS PORT MAP(AIN, BIN, FUNC, HIREG, LOREG, ROUT, STAT);
	
END ARCHITECTURE;